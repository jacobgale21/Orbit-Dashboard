const series = (base: number, drift: number, n = 8) =>
  Array.from({ length: n }, (_, i) => ({
    t: `${2024 + Math.floor(i / 4)} Q${(i % 4) + 1}`,
    v:
      Math.round((base + drift * i + Math.sin(i * 1.7) * base * 0.06) * 100) /
      100,
  }));

const earn = (base: number, growth: number, margin: number) =>
  Array.from({ length: 6 }, (_, i) => {
    const rev = Math.round(base * Math.pow(1 + growth, i));
    return {
      q: `Q${(i % 4) + 1}'${24 + Math.floor(i / 4)}`,
      rev,
      profit: Math.round(rev * margin),
    };
  });

